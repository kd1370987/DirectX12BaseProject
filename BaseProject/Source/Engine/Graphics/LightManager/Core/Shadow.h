#pragma once

//==========================================================================================
//
// 平行光(主光源)の影
//
// 影の求め方は2通りあり、シーンごとに切り替えられる。
//   Raytracing : 画面のピクセルごとに主光源へレイを飛ばす(RaytracingShadowPass)
//   ShadowMap  : 光源から見た深度を描いておき、それと比べる(ShadowMapPass → ShadowMapMaskPass)
//
// どちらも同じ「影マスク」を作るので、ディファードは求め方を知らなくてよい。
// パイプラインには両方のパスを置いたままにしておき、使わない側は何もしない。
//
// 設定の持ち主はシーン(Engine::Scene::SceneAmbient)で、毎フレーム LightManager へ流し込む。
// ホーム画面はレイトレ、ゲーム中はシャドウマップ、のように場面で使い分けるため
//
//==========================================================================================
namespace Engine::Graphics
{
	// 平行光の影の求め方
	// ※ シーンへ数値で保存しているので、並びを変えないこと。足すときは末尾へ
	enum class EDirectionalShadowMode : uint8_t
	{
		Raytracing,		// レイトレーシング
		ShadowMap,		// シャドウマップ(カスケード)
	};

	// カスケードの最大数。
	// シャドウマップは 2x2 のタイルに分けた1枚のアトラスなので、4 が上限
	inline constexpr uint32_t MAX_SHADOW_CASCADES = 4;

	//======================================================================================
	// 平行光の影の設定 : シーンの持ち物
	//======================================================================================
	struct DirectionalShadowSettings
	{
		EDirectionalShadowMode mode = EDirectionalShadowMode::Raytracing;

		// カメラからどこまで影を落とすか(ビュー空間の奥行き)。
		// これより奥は影なしになる。シャドウマップでは広げるほど1テクセルが粗くなる。
		// ボリュメトリックフォグはどちらの求め方でもここまで影を引く(レイトレでは広げるほどレイの間隔が粗くなる)
		float distance = 80.0f;

		//----------------------------------------------------------------------------------
		// 以下はシャドウマップのときだけ使う
		//----------------------------------------------------------------------------------

		// カスケードの数(1～MAX_SHADOW_CASCADES)。
		// 手前ほど細かいカスケードに入るので、数を増やすほど足元の影がくっきりする
		uint32_t cascadeCount = 3;

		// カスケードの区切り方 : 0 で等間隔、1 で対数(手前に寄せる)
		float splitLambda = 0.75f;

		// 深度の比較にかける余裕(ワールドの長さ)。
		// 小さすぎると面に縞(シャドウアクネ)が出て、大きすぎると影が接地面から浮く
		float depthBias = 0.05f;

		// 比べる位置を法線方向へずらす量(テクセル数)。
		// 斜面のアクネを消す。大きすぎると細い物の影が痩せる
		float normalBias = 1.5f;

		// 影の縁のぼかし幅(テクセル数)。0 で PCF の最小(バイリニア1回)になる
		float softness = 1.0f;

		// カスケードの箱から光源側へ、どこまで遮蔽物を拾うか(ワールドの長さ)。
		// 画面の外(背後の崖など)から落ちてくる影を拾うための余白
		float casterDistance = 150.0f;
	};

	//======================================================================================
	// シャドウマップの定数バッファ
	//
	// LightManager::BuildShadowCascades() がカメラから毎フレーム組む。
	// ※ HLSL 側 Asset/Shader/Common/RootParameters/ShadowMapData.hlsli と並びを合わせること。
	//    cbuffer なので16バイト行に揃える
	//======================================================================================
	struct SunShadowCB
	{
		// カスケードごとのライトのビュー射影(転置済み)
		Math::Matrix lightViewProj[MAX_SHADOW_CASCADES] = {};

		// カスケードごとの値。要素 i がカスケード i
		Math::Vector4 cascadeFar = {};			// このカスケードが受け持つ奥行きの終わり(ビュー空間Z)
		Math::Vector4 cascadeBlendStart = {};	// ここから次のカスケードへ混ぜ始める(ビュー空間Z)
		Math::Vector4 cascadeRadius = {};		// 箱の半径(ワールド) : テクセルの大きさを出すのに使う
		Math::Vector4 cascadeDepthRange = {};	// 箱の奥行き(ワールド) : 深度バイアスを射影後の値へ直すのに使う

		Math::Vector3 lightDir = { 0.0f, -1.0f, 0.0f };	// 光の進む向き
		uint32_t cascadeCount = 0;						// 0 なら影なし(全部ひなた)

		float depthBias = 0.0f;
		float normalBias = 0.0f;
		float softness = 0.0f;
		float pad = 0.0f;
	};
}
