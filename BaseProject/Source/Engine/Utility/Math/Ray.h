#pragma once

#include "Vector/Vector3.h"

//==========================================================================================
// Math::Ray
//
// 始点・向き・最大距離だけを持つレイ。
// 当たり判定(Engine::Collision)の持ち物だったが、エディターのピッキングやカメラの
// スクリーン→ワールド変換でも使うので、判定の実装から切り離してここへ置いている。
// Engine::Collision::RayInfo はこの型の別名。
//==========================================================================================
namespace Math
{
	struct Ray
	{
		Vector3 origin = { 0.0f,0.0f,0.0f };
		Vector3 direction = { 0.0f,0.0f,1.0f };	// 正規化は使う側の責任(AABB判定は単位ベクトル前提)
		float maxDistance = 1000.0f;
	};
}
