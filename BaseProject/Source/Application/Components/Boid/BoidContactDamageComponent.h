#pragma once

//==========================================================================================
// BoidContactDamageComponent
//
// ワームの体(ボイド)がプレイヤーに触れたときにダメージを与えるための状態。
//
// ・付けるのは SwarmBossController(ボイドの生成時)。プレハブには入れない。
// ・持つのは「次に判定を始めるまでの残り時間」だけ。ダメージ量などの設定は
//   SwarmContactDamageResource にまとめてあり、4000体で共有する。
// ・ダメージを与えたら cooldown 秒は判定しない(ボイドごと)。
//   触れ続けても毎フレーム削られないようにするため。
// ・判定とダメージは BoidContactDamageSystem。実行中の値だけなので保存しない。
//==========================================================================================
struct BoidContactDamageComponent
{
	float cooldownTimer = 0.0f;		// 次に判定を始めるまでの残り時間(秒)
};
