#pragma once

//==========================================================================================
//
// ワームの体(ボイド)がプレイヤーに触れたときのダメージの設定と、プレイヤーの判定の形。
//
// 書くのは SwarmBossController(調整値と、毎フレーム探したプレイヤーのカプセル)。
// 受けて 4000 体ぶんの接触を見るのは BoidContactDamageSystem。
// 間にこのリソースを挟んでいるのはウェーブ(WormWaveResource)と同じ理由で、
// オブジェクト側の更新で ECS を全走査するとチャンク単位で回れないため。
//
// 接触は物理のクエリを使わず、ボイドの位置とプレイヤーのカプセル(縦の線分 + 半径)の
// 距離だけで見る。4000 体ぶんクエリを打つより桁違いに軽く、相手はプレイヤー1体だけなので足りる。
//
//==========================================================================================

struct SwarmContactDamageResource
{
	//--------------------------------------------------------------------------
	// 調整値(SwarmBossController が毎フレーム書き写す)
	//--------------------------------------------------------------------------
	float damage     = 5.0f;	// ボイド1体が1回触れたときのダメージ
	float cooldown   = 1.0f;	// ダメージを与えたボイドが、次に判定を始めるまでの時間(秒)
	float boidRadius = 1.0f;	// ボイドの接触半径(m)

	//--------------------------------------------------------------------------
	// プレイヤー(SwarmBossController が毎フレーム書く)
	//--------------------------------------------------------------------------
	Engine::ECS::Entity player = Engine::ECS::Limits::INVALID_ENTITY;
	Math::Vector3 playerSegmentA = {};	// カプセルの下端の球の中心(ワールド)
	Math::Vector3 playerSegmentB = {};	// 上端の球の中心(ワールド)
	float playerRadius = 0.0f;			// カプセルの半径

	// ボスが居て、プレイヤーも見つかっているか。false の間は何もしない
	bool isActive = false;

	void Clear()
	{
		player   = Engine::ECS::Limits::INVALID_ENTITY;
		isActive = false;
	}
};
