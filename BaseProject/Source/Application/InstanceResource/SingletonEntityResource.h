#pragma once

//==========================================================================================
//
// ワールドに1つしか居ない役のエンティティを覚えておくワールドリソース。
//
// 「そのフレームの主役はどれか」をタグで表していたころは、
// 使う側が毎回 ForEach でタグ付きのエンティティを探し直していた。
// 探し方(クエリの条件)が使う側ごとにばらけるので、
// 条件を1つ足し忘れただけで「片方のシステムだけ別のカメラを見ている」が起きる。
//
// ここに1本だけ答えを置き、決める係(MainCameraSystem など)が毎フレーム書く。
// 使う側は entity を受け取って RefData で引くだけにする。
//
// ・ここに入るのは「役」であって「持ち物」ではない。
//   種類が増えたらメンバーを足していく(メインカメラ、プレイヤー…)。
// ・エンティティは消えることがあるので、引く前に必ず
//   IsAliveEntity / HasComponent を通すこと。
//   前フレームに死んだ相手の添え字がそのまま残っている場合がある。
//
//==========================================================================================
struct SingletonEntityResource
{
	//======================================================================================
	// メインカメラ
	//--------------------------------------------------------------------------------------
	// 画面を映しているカメラ。MainCameraSystem が PreUpdate で毎フレーム決め直す。
	// カメラが1台も居ないフレーム(シーン切り替えの間など)は INVALID_ENTITY のまま。
	//======================================================================================
	Engine::ECS::Entity mainCamera = Engine::ECS::Limits::INVALID_ENTITY;

	// メインカメラが居るかどうか
	bool HasMainCamera() const
	{
		return mainCamera != Engine::ECS::Limits::INVALID_ENTITY;
	}

	// 全部を無効に戻す
	void Clear()
	{
		mainCamera = Engine::ECS::Limits::INVALID_ENTITY;
	}
};
