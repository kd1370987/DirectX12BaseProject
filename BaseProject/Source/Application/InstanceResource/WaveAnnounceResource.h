#pragma once

//==========================================================================================
//
// 「何番目のウェーブが出たか」を置いておくワールドリソース。
//
// 積む : SceneSequence(ウェーブを出した瞬間に1回)
// 読む : WaveAnnounceHUD(表示と音)
//
// HitEventResource のような配列(1フレーム分を貯めて次のフレームに捨てる)にはしていない。
// 読むのが UI(GameObjectManager::Update)で、積むのも UI と同じ帯にいる SceneSequence
// だから、両者の順番はシーンに置いたオブジェクトの並び順で決まってしまう。
// 配列＋クリア方式だと、HUD のほうが先に回るシーンでは積まれた回に気づけないまま
// 捨てられて、ウェーブの表示が一度も出ないことがある。
//
// そこで「最後に出たウェーブ」と、出るたびに増える通し番号だけを持たせている。
// 読む側は前回見た通し番号を覚えておき、違っていたら1回反応する。
// 遅れて読んでも取りこぼさないので、クリアする係も要らない。
//
//==========================================================================================
struct WaveAnnounceResource
{
	// 最後に出たウェーブ(0始まり)。まだ何も出ていなければ -1
	int waveIndex = -1;

	// そのシーンのウェーブ総数。「3 / 6」のように出したいとき用
	int waveCount = 0;

	// 出るたびに増える通し番号。読む側はこの値の変化だけを見る
	uint32_t serial = 0;

	// ウェーブが出たことを知らせる
	void Push(int a_waveIndex, int a_waveCount)
	{
		waveIndex = a_waveIndex;
		waveCount = a_waveCount;
		++serial;
	}
};
