//   ・エンジンのシーン管理がゲーム側の登録処理を持ち回る形になっていた
//   ・GameManager::Init が451行まで膨らんでいた
// ため、App::ECS::World::RegisterGameTypes から直接呼ぶ形へ寄せている。
//
// 新しいコンポーネントやシステムを足したら、ここに1行足すこと。
//
//==========================================================================================

